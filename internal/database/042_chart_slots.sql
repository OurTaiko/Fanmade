-- A chart's blocks are slots of course × side, as on the arcade machine, where
-- every course has a single, a 1P and a 2P chart that may all differ. One row
-- per block the stored TJA really contains; the file itself stays whole.
-- Replaces charts.difficulties and charts.is_single, so single and double
-- blocks may share a file.
--
-- Which block a player reads is the client's rule, not a constraint here:
--   single play     single → p1
--   two players, 1P p1 → single
--   two players, 2P p2 → single → p1
CREATE TABLE chart_difficulties (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chart_id text NOT NULL REFERENCES charts(id) ON DELETE CASCADE,
 course text NOT NULL CHECK(course IN ('Easy','Normal','Hard','Oni','Edit')),
 -- The block's #START: plain = single, #START P1 = p1, #START P2 = p2.
 side text NOT NULL CHECK(side IN ('single','p1','p2')),
 level smallint NOT NULL CHECK(level BETWEEN 1 AND 10),
 branching boolean NOT NULL DEFAULT false,
 maker text NOT NULL DEFAULT '' CHECK(octet_length(maker)<=500),
 UNIQUE(chart_id,course,side)
);
CREATE INDEX chart_difficulties_course_level ON chart_difficulties(course,level,chart_id);
-- Archived Tower/Dan entries have no slot. Their songs were never listed and
-- stay withdrawn now that the entries no longer mark them.
ALTER TABLE charts DROP CONSTRAINT charts_difficulties_check;
UPDATE charts c SET status='hidden' WHERE c.status='published' AND EXISTS(
 SELECT 1 FROM jsonb_array_elements(c.difficulties) d WHERE d->>'course' !~ '^(Easy|Normal|Hard|Oni|Edit)(_[12]p)?$');
SET CONSTRAINTS ALL IMMEDIATE;
INSERT INTO chart_difficulties(chart_id,course,side,level,branching,maker)
SELECT c.id,regexp_replace(d->>'course','_[12]p$',''),
 CASE WHEN d->>'course' ~ '_1p$' THEN 'p1' WHEN d->>'course' ~ '_2p$' THEN 'p2' ELSE 'single' END,
 (d->>'level')::smallint,COALESCE((d->>'branching')::boolean,false),d->>'maker'
 FROM charts c,jsonb_array_elements(c.difficulties) WITH ORDINALITY AS t(d,position)
 WHERE d->>'course' ~ '^(Easy|Normal|Hard|Oni|Edit)(_[12]p)?$'
 ORDER BY c.created_at,c.id,t.position;

-- A score records the block that was really played. Replacing a song's files
-- used to delete its scores, so every stored score is of the current files.
ALTER TABLE scores ADD COLUMN difficulty_id bigint REFERENCES chart_difficulties(id),
 ADD COLUMN is_latest boolean NOT NULL DEFAULT true;
UPDATE scores s SET difficulty_id=d.id FROM chart_difficulties d
 WHERE d.chart_id=s.song_id AND d.course=regexp_replace(s.difficulty,'_[12]p$','')
 AND d.side=CASE WHEN s.difficulty ~ '_1p$' THEN 'p1' WHEN s.difficulty ~ '_2p$' THEN 'p2' ELSE 'single' END;
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM scores WHERE difficulty_id IS NULL) THEN
  RAISE EXCEPTION 'migration 042: scores of unsupported difficulties must be resolved first';
 END IF;
END $$;
