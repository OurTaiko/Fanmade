-- Every chart gets a number_id besides its ID, as on OurTaiko Database: the existing charts are
-- numbered 1, 2, 3… in a random order, later ones count on from there. GET /charts/{id} finds a
-- chart by this number unless told by=id.
ALTER TABLE charts ADD COLUMN number_id bigint;
WITH shuffled AS (SELECT id, row_number() OVER (ORDER BY random()) AS n FROM charts)
UPDATE charts c SET number_id = shuffled.n FROM shuffled WHERE shuffled.id = c.id;
ALTER TABLE charts ALTER COLUMN number_id SET NOT NULL,
  ADD CONSTRAINT charts_number_id_key UNIQUE (number_id),
  ALTER COLUMN number_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('charts', 'number_id'), (SELECT max(number_id) FROM charts))
 WHERE EXISTS (SELECT 1 FROM charts);
